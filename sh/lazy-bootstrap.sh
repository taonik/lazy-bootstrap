NOTES=()
COMMAND="${1:-}"; shift || true
case "$COMMAND" in
    -h|--help|help|"") usage; exit 0 ;;
    doctor|inventory|rebuild) ;;
    *) die "unknown command: $COMMAND (try --help)" ;;
esac

while [ $# -gt 0 ]; do
    case "$1" in
        -b|--backend)        BACKEND="$2"; shift 2 ;;
        --rootfs)            ROOTFS="$2"; shift 2 ;;
        --rootfs-path)       ROOTFS_PATH="$2"; shift 2 ;;
        --workdir)           WORKDIR="$2"; shift 2 ;;
        -t|--toolchain)      TOOLCHAIN="$2"; shift 2 ;;
        --package)           SELECT+=("$2"); shift 2 ;;
        --limit)             LIMIT="$2"; shift 2 ;;
        --registry-mirror)   REGISTRY_MIRROR="$2"; shift 2 ;;
        --source-mirror)     SOURCE_MIRROR="$2"; shift 2 ;;
        --system-deps)       SYSTEM_DEPS="$2"; shift 2 ;;
        --out-dir)           OUT_DIR="$2"; shift 2 ;;
        --cache-dir)         CACHE_DIR="$2"; shift 2 ;;
        --timeout)           TIMEOUT="$2"; shift 2 ;;
        -d|--debug)          LB_DEBUG=$((LB_DEBUG + 1)); shift ;;
        -h|--help)           usage; exit 0 ;;
        -*)                  die "unknown option: $1" ;;
        *)                   IMAGE="$1"; shift ;;
    esac
done

[ "$BACKEND" = host ] || [ "$COMMAND" = doctor ] || [ -n "$IMAGE" ] || \
    case "$ROOTFS" in dir:*|none) ;; *) die "an image is required" ;; esac

case "$COMMAND" in
    doctor)    cmd_doctor ;;
    inventory) cmd_inventory ;;
    rebuild)   cmd_rebuild ;;
esac
