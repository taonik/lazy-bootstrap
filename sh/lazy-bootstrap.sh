cmd_doctor() {
    say "backends"
    local b
    for b in podman docker bwrap firejail chroot; do
        if command -v "$b" >/dev/null 2>&1; then printf '  [ok ] %-10s %s\n' "$b" "$(command -v "$b")"
        else printf '  [-- ] %-10s not installed\n' "$b"; fi
    done
    printf '  [ok ] %-10s uid=%s\n' host "$(id -u)"
    say "helpers"
    for b in curl tar xz git patchelf mount python3; do
        if command -v "$b" >/dev/null 2>&1; then printf '  [ok ] %-10s\n' "$b"
        else printf '  [-- ] %-10s not installed\n' "$b"; fi
    done
    say "network"
    local h
    for h in https://github.com/ https://mirror.gcr.io/v2/ https://deb.debian.org/debian/dists/ \
             https://dl-cdn.alpinelinux.org/alpine/ http://archive.ubuntu.com/ubuntu/dists/; do
        local code; code="$(curl -sS -o /dev/null -w '%{http_code}' -I --max-time 10 "$h" 2>/dev/null)"
        case "$code" in 2*|3*|401|404|405) printf '  [ok ] %-45s %s\n' "$h" "$code" ;;
                        *) printf '  [-- ] %-45s %s\n' "$h" "$code" ;; esac
    done
}

cmd_inventory() {
    env_open; trap env_close EXIT
    detect_distro
    local total=0
    while IFS=$'\t' read -r name version arch source || [ -n "$name" ]; do
        [ -n "$name" ] || continue
        total=$((total + 1))
        if [ "$source" != "$name" ] && [ -n "$source" ]; then
            printf '  %-34s %-26s  <- %s\n' "$name" "$version" "$source"
        else
            printf '  %-34s %s\n' "$name" "$version"
        fi
    done < <(distro_inventory)
    printf '\n%s binary packages\n' "$total"
}

cmd_rebuild() {
    STARTED_AT="$(date -u +%Y-%m-%dT%H:%M:%S+00:00)"
    local run_id; run_id="$(printf '%s-%s-%s' \
        "$(printf '%s' "${IMAGE:-host}" | tr -c 'a-zA-Z0-9._-' '-')" \
        "$(printf '%s' "$TOOLCHAIN" | tr -c 'a-zA-Z0-9._-' '-')" "$(date +%s)")"
    mkdir -p "$OUT_DIR/$run_id"
    replay_init "$OUT_DIR/$run_id/replay/all.sh"

    env_open; trap env_close EXIT
    detect_distro

    say "toolchain: $TOOLCHAIN"
    toolchain_provision "$TOOLCHAIN"
    if ! toolchain_probe; then
        die "toolchain $TOOLCHAIN cannot compile a hello world - fix that first"
    fi
    info "toolchain ok: $TC_CC ($TC_VERSION, from $TC_SOURCE)"

    say "preparing the build environment"
    prepare_builder

    # binary -> source, deduplicated: one build per source package (D-10)
    local -A SOURCE_OF=() VERSION_OF=() ARCH_OF=()
    local -a sources=()
    while IFS=$'\t' read -r name version arch source || [ -n "$name" ]; do
        [ -n "$name" ] || continue
        source="${source:-$name}"
        if [ "${#SELECT[@]}" -gt 0 ]; then
            local keep=0 s
            for s in "${SELECT[@]}"; do
                [ "$s" = "$name" ] || [ "$s" = "$source" ] && keep=1
            done
            [ "$keep" = 1 ] || continue
        fi
        SOURCE_OF["$name"]="$source"; VERSION_OF["$name"]="$version"; ARCH_OF["$name"]="$arch"
        case " ${sources[*]:-} " in *" $source "*) ;; *) sources+=("$source") ;; esac
    done < <(distro_inventory)

    [ "$LIMIT" -gt 0 ] && sources=("${sources[@]:0:$LIMIT}")
    say "rebuilding ${#sources[@]} source package(s)"

    RESULTS_JSON=""
    local ok=0 bad=0 source name
    for source in "${sources[@]}"; do
        build_source "$source"
        case "$BUILD_STATUS" in ok) ok=$((ok + 1)) ;; *) bad=$((bad + 1)) ;; esac
        printf '  %-34s %-9s %ss\n' "$source" "$BUILD_STATUS" "$BUILD_SECONDS"
        for name in "${!SOURCE_OF[@]}"; do
            [ "${SOURCE_OF[$name]}" = "$source" ] || continue
            result_json "$name" "${VERSION_OF[$name]}" "${ARCH_OF[$name]}" "$source" \
                        "$BUILD_STATUS" "$BUILD_SECONDS" "$(printf '%s' "$BUILD_ERROR" | tail -c 2000)"
        done
    done

    local path; path="$(write_report "$run_id")"
    say "done: $ok ok, $bad failed"
    printf 'report: %s\n' "$path"
    printf 'replay: %s\n' "$REPLAY"
    printf '\nrender it with:\n  ./lazy-bootstrap report %s --format html -o report.html\n' \
        "$OUT_DIR/$run_id"
    [ "$bad" -eq 0 ]
}

usage() {
    cat <<EOF
$SELF $VERSION - rebuild the packages of a distro image (shell edition)

  $SELF doctor
  $SELF inventory <image> [options]
  $SELF rebuild   <image> [options]

Options
  -b, --backend NAME       host | chroot | bwrap | firejail | podman | docker
      --rootfs SPEC        image[:REF] | dir:PATH | none
      --rootfs-path PATH   where to materialise the rootfs
      --workdir PATH       build directory inside the environment
  -t, --toolchain ID       gcc | llvm[-VER] | filc[-VER]        (default: gcc)
      --package NAME       only this package/source (repeatable)
      --limit N            build at most N source packages
      --registry-mirror H  e.g. mirror.gcr.io
      --source-mirror SPEC apt: "URL suite components"; apk: aports branch
      --system-deps POLICY off | target | host                  (default: target)
      --out-dir DIR        where reports go                     (default: runs)
      --timeout SECONDS    per package                          (default: 1800)
  -d, --debug              repeatable: -d steps, -dd payloads, -ddd full output

Environment
  LB_DEBUG=0..3            same as --debug
  LB_SHIM_TRACE=1          echo every compiler invocation from inside the build
EOF
}

# --------------------------------------------------------------------------
# argument parsing
